func TestFetchQueryRoutesS3CSVThroughGatewayBatches(t *testing.T) {
	const csvData = "generated by fixture\nid|name|active\n1|Ada|true\n2|Lin|false\n3|Grace|true\n4|Edsger|true\n5|Barbara|true\n"
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/demo-bucket/data.csv" {
			http.NotFound(w, r)
			return
		}
		if r.Method == http.MethodHead {
			w.Header().Set("Content-Length", fmt.Sprint(len(csvData)))
			w.WriteHeader(http.StatusOK)
			return
		}
		if r.Method != http.MethodGet {
			http.Error(w, "unsupported method", http.StatusMethodNotAllowed)
			return
		}
		_, _ = io.WriteString(w, csvData)
	}))
	defer server.Close()

	source := &model.DataSource{
		ID: "s3-csv-query-service-test", Type: model.DatabaseTypeS3CSV, Status: model.DataSourceStatusActive,
		Config: model.DataSourceConfig{
			Host: "data.csv", Port: 443, Database: "demo-bucket", Username: "test-access-key", Password: "test-secret-key",
			AdditionalProps: map[string]interface{}{
				"object_key": "data.csv", "table_name": "records", "region": "us-east-1",
				"endpoint_url": server.URL, "force_path_style": true, "delimiter": "|", "skip_header_rows": 1,
			},
		},
	}
	pool := database.NewConnectionPool(database.NewDriverRegistry(), nil, nil, false)
	defer pool.CloseAll()
	queryService := NewQueryService(federationSourceRepository{source: source}, pool, false, newTestSQLTranslationManager())
	ctx := context.Background()
	response, err := queryService.FetchQuery(ctx, nil, &model.FetchQueryRequest{
		DataSourceID: source.ID,
		SQL:          "SELECT id, name FROM records WHERE active = true ORDER BY id DESC",
		Type:         2,
		BatchSize:    2,
	})
	if err != nil {
		t.Fatalf("FetchQuery() error = %v", err)
	}
	if response.TotalCount != 4 || len(response.Entries) != 2 || response.NextURI == "" {
		t.Fatalf("first response total=%d entries=%d next=%q, want 4 rows in two-row first batch", response.TotalCount, len(response.Entries), response.NextURI)
	}
	if len(response.Columns) != 2 || response.Columns[0].Name != "id" || response.Columns[1].Name != "name" {
		t.Fatalf("first response columns = %+v, want id,name projection", response.Columns)
	}
	assertS3CSVServiceRows(t, response.Entries, []int64{5, 4}, []string{"Barbara", "Edsger"})

	second, err := queryService.FetchNextBatch(ctx, nil, response.QueryID, response.Slug, response.Token, 2)
	if err != nil {
		t.Fatalf("FetchNextBatch() error = %v", err)
	}
	if second.TotalCount != 4 || len(second.Entries) != 2 || second.NextURI != "" {
		t.Fatalf("second response total=%d entries=%d next=%q, want final two-row batch", second.TotalCount, len(second.Entries), second.NextURI)
	}
	assertS3CSVServiceRows(t, second.Entries, []int64{3, 1}, []string{"Grace", "Ada"})
}

func TestFetchQueryCancellationStopsS3CSVDownload(t *testing.T) {
	getStarted := make(chan struct{})
	var getStartedOnce sync.Once
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method == http.MethodHead {
			w.WriteHeader(http.StatusOK)
			return
		}
		getStartedOnce.Do(func() { close(getStarted) })
		<-r.Context().Done()
	}))
	defer server.Close()

	source := &model.DataSource{
		ID: "s3-csv-query-service-cancel-test", Type: model.DatabaseTypeS3CSV, Status: model.DataSourceStatusActive,
		Config: model.DataSourceConfig{
			Host: "data.csv", Port: 443, Database: "demo-bucket", Username: "test-access-key", Password: "test-secret-key",
			AdditionalProps: map[string]interface{}{
				"object_key": "data.csv", "table_name": "records", "region": "us-east-1",
				"endpoint_url": server.URL, "force_path_style": true,
			},
		},
	}
	pool := database.NewConnectionPool(database.NewDriverRegistry(), nil, nil, false)
	defer pool.CloseAll()
	queryService := NewQueryService(federationSourceRepository{source: source}, pool, false, newTestSQLTranslationManager())
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	result := make(chan error, 1)
	go func() {
		_, err := queryService.FetchQuery(ctx, nil, &model.FetchQueryRequest{
			DataSourceID: source.ID, SQL: "SELECT * FROM records", Type: 1, BatchSize: 10,
		})
		result <- err
	}()

	select {
	case <-getStarted:
	case <-time.After(2 * time.Second):
		t.Fatal("query did not start its object download")
	}
	cancel()
	select {
	case err := <-result:
		if err == nil {
			t.Fatal("FetchQuery() succeeded after its context was cancelled")
		}
	case <-time.After(2 * time.Second):
		t.Fatal("FetchQuery() did not return after cancellation")
	}
}

func assertS3CSVServiceRows(t *testing.T, entries []*[]interface{}, wantIDs []int64, wantNames []string) {
	t.Helper()
	if len(entries) != len(wantIDs) || len(entries) != len(wantNames) {
		t.Fatalf("entry count = %d, want %d", len(entries), len(wantIDs))
	}
	for i, entry := range entries {
		if entry == nil || len(*entry) != 2 {
			t.Fatalf("entry %d = %v, want [id, name]", i, entry)
		}
		id, ok := (*entry)[0].(int64)
		if !ok || id != wantIDs[i] || (*entry)[1] != wantNames[i] {
			t.Fatalf("entry %d = %#v, want [%d %q]", i, *entry, wantIDs[i], wantNames[i])
		}
	}
}
